
# Creating a list of student names
students = ["Ahmed", "Sara", "Ali", "Zara", "Usman"]

# Displaying the original list
print("Original student list:", students)

# Adding a new student
students.append("Hamza")
print("After adding a student:", students)

# Removing a student
students.remove("Ali")
print("After removing a student:", students)

# Accessing an element
print("First student:", students[0])

# Sorting the list
students.sort()
print("Sorted student list:", students)

# Displaying total students
print("Total students:", len(students))
